/** Грубая основа слова: «круассан» и «круассаны», «помидор» и «помидоры» дают одну основу. */
const stem = (w: string) => (w.length > 4 ? w.replace(/(ами|ями|ов|ев|ей|ы|и|а|я|ь|о|е|у|ю)$/u, '') : w);
const STEM_INDEX: Map<string, string> = (() => {
  const m = new Map<string, string>();
  for (const k of Object.keys(HINTS_PLN)) {
    const s = k.split(' ').map(stem).join(' ');
    if (!m.has(s)) m.set(s, k);
  }
  return m;
})();

function findHintKey(key: string): string | null {
  if (HINTS_PLN[key]) return key;
  if (SYNONYMS[key]) return SYNONYMS[key];
  const stemmed = key.split(' ').map(stem).join(' ');
  if (STEM_INDEX.has(stemmed)) return STEM_INDEX.get(stemmed)!;
  // «Молоко 3.2%» → «молоко», «Сыр гауда» → «сыр»: самое длинное совпадение с начала названия
  const prefix = [...Object.keys(HINTS_PLN), ...Object.keys(SYNONYMS)]
    .filter(k => key.startsWith(k + ' '))
    .sort((a, b) => b.length - a.length)[0];
  if (prefix) return SYNONYMS[prefix] || prefix;
  // По основе первого слова: «Круассан шоколадный» → «круассаны»
  const first = stem(key.split(' ')[0]);
  return STEM_INDEX.get(first) || null;
}

/** Каноническое название из справочника: «Орешки» → «орехи», «Морковь (морковка)» → «морковь»; null — не знаем. */
export function canonicalKey(name: string): string | null {
  return findHintKey(cleanName(name)) || findHintKey(normName(name));
}

/** Цена за `price` единиц `from`, пересчитанная на единицу `to`; null, если единицы несовместимы. */
export function convertUnitPrice(price: number, from: Unit, to: Unit): number | null {
  if (from === to) return price;
  const factor: Record<string, number> = {
    'кг>г': 1 / 1000, 'л>мл': 1 / 1000, 'г>кг': 1000, 'мл>л': 1000,
    // для ориентира «штука» и «упаковка» считаются одним и тем же
    'шт>уп': 1, 'уп>шт': 1,
    // напитки: бутылка ≈ литр
    'л>шт': 1,
  };
  const f = factor[from + '>' + to];
  return f ? price * f : null;
}

