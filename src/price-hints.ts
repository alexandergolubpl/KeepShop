/** «Морковь (морковка)» → «морковь», «Арбуз / дыня» → «арбуз», «Огурцы свежий» остаётся как есть. */
function cleanName(name: string): string {
  return normName(String(name || '').replace(/\([^)]*\)/g, ' ').split('/')[0]);
}

/** Типичная цена товара за единицу `unit` (или за его «родную» единицу, если unit не задан). */
export function hintPrice(name: string, unit?: Unit): { price: number; unit: Unit } | null {
  const hintKey = findHintKey(cleanName(name)) || findHintKey(normName(name));
  const hint = hintKey ? HINTS_PLN[hintKey] : undefined;
  if (!hint) return null;
  const [price, hintUnit] = hint;
  if (!unit || unit === hintUnit) return { price, unit: hintUnit };
  let converted = convertUnitPrice(price, hintUnit, unit);
  if (converted == null && hintUnit === 'кг' && unit === 'шт' && PIECE_KG[hintKey!]) converted = price * PIECE_KG[hintKey!];
  return converted == null ? null : { price: Math.round(converted * 100) / 100 || Math.round(converted * 10000) / 10000, unit };
}
